def _obk_load_move_weights(obk_path: str) -> dict:
    """从 SQLite 版 OBK（bhobk 表）聚合出 move_int → (正权重, 胜, 和, 负)。

    利用：OBK 的 vmove 整数编码与全球 Xiangqi Polyglot 4bit 编码一致。
    胜/和/负统计用于真实难度分层（和棋率高=平稳定式；胜负分明+低频=飞刀）。
    """
    import sqlite3
    try:
        con = sqlite3.connect(obk_path)
        cur = con.cursor()
        # 直接用 SQL 聚合，一次性返回，避免 Python 遍历 233 万行
        cur.execute("""
            SELECT vmove,
                   SUM(
                       CASE WHEN (vscore*100 + vwin*20 + vdraw*5 - vlost*2) > 0
                            THEN (vscore*100 + vwin*20 + vdraw*5 - vlost*2)
                            ELSE 0 END
                   ) AS total_w,
                   COALESCE(SUM(vwin), 0),
                   COALESCE(SUM(vdraw), 0),
                   COALESCE(SUM(vlost), 0)
            FROM bhobk
            WHERE vvalid=1
            GROUP BY vmove
            HAVING total_w > 0
        """)
        wmap = {mv: (w, win, draw, lost)
                for mv, w, win, draw, lost in cur.fetchall() if w and w > 0}
        con.close()
        return wmap
    except Exception as e:
        return {"__err__": str(e)}


def _move_int_from_pos(frm, to) -> int:
    """Pos(frm, to) → Xiangqi Polyglot move 整数编码（和 OBK vmove 同编码）。
    ff=frm.col, fr=9-frm.row, tf=to.col, tr=9-to.row; mv = (ff<<12)|(fr<<8)|(tf<<4)|tr
    """
    ff = frm.col & 0xF
    fr = (9 - frm.row) & 0xF
    tf = to.col & 0xF
    tr = (9 - to.row) & 0xF
    return (ff << 12) | (fr << 8) | (tf << 4) | tr


