def _cands_from_wmap(board, wmap: dict, topk: int = 10, ply_hint: int = 0):
    """当前 board 上所有合法走子 → 查 wmap 权重 → 加上开局主招大奖励/惩罚 → 按权重降序取 topk。
    ply_hint: 当前半步深度（0=start,1=黑1...），用于惩罚逻辑分级。
    返回 (ucci, final_w, stats) 三元组列表；stats=(base_w, win, draw, lost) 供难度分层。
    """
    from ..board import rules as _rules
    from ..board.rules import generate_legal_moves
    from ..board.pieces import PieceType as _PT, Color as _CLR
    cands = []
    side = getattr(board, "side", None) or getattr(board, "turn", None)
    moves = generate_legal_moves(board, side)
    EARLY = ply_hint < 14
    for frm, to in moves:
        try:
            if not _rules.is_legal(board, frm, to):
                continue
        except Exception:
            continue
        mvi = _move_int_from_pos(frm, to)
        t = wmap.get(mvi)
        if t is not None:
            base_w, bwin, bdraw, blost = int(t[0]), int(t[1]), int(t[2]), int(t[3])
        else:
            base_w, bwin, bdraw, blost = 0, 0, 0, 0
        ucci = (chr(ord('a') + frm.col) + str(9 - frm.row) +
                chr(ord('a') + to.col) + str(9 - to.row))
        bonus = _MAIN_OPENING_BONUS.get(ucci, 0)
        final_w = base_w // 100 + bonus * 100  # OBK全局权重缩小100倍，奖励主导前10步
        if EARLY:
            piece = board.get(frm)
            if piece is not None:
                ptype = piece.type
                # 1. 炮开局乱发过河且不在奖励列表 → 大罚
                if ptype is _PT.CANNON:
                    red_p = (piece.color is _CLR.RED)
                    crossed = (red_p and to.row < 5) or ((not red_p) and to.row >= 5)
                    if crossed and bonus == 0:
                        final_w -= 2_000_000
                    if frm.row == to.row and abs(frm.col - to.col) == 2 and bonus == 0:
                        final_w -= 500_000
                # 2. 兵卒连续挺（非奖励表的挺兵且OBK权重本身也低 → 大罚）
                if ptype is _PT.PAWN:
                    if bonus == 0 and base_w // 100 < 5000:
                        final_w -= 1_500_000
                # 3. 开局动帅/士/相太早且无奖励 → 超大罚
                if ptype in (_PT.KING, _PT.ADVISOR, _PT.ELEPHANT):
                    if ply_hint < 8 and bonus == 0:
                        final_w -= 3_000_000
        if final_w < 100:
            final_w = 100
        cands.append((ucci, final_w, (base_w, bwin, bdraw, blost)))
    cands.sort(key=lambda x: -x[1])
    seen = set()
    uniq = []
    for u, fw, st in cands:
        if u in seen:
            continue
        seen.add(u)
        uniq.append((u, fw, st))
        if len(uniq) >= topk:
            break
    return uniq


def obk_to_lessons(
    obk_path: str,
    *,
    difficulty: int = 2,
    max_lessons: int = 120,
    min_steps: int = 8,
    start_id_prefix: str = "obk",
) -> tuple[list[OpeningLesson], list[str]]:
    """读入秦大 OBK 开局库 → 开局课（带本地 pickle 缓存）。

    首次解析大文件（如 146MB 玫瑰飞刀库）约需百秒级；成功后把结果落盘到
    `<obk文件>.pkl.cache`（含源文件大小/mtime+全部生成参数的 meta 校验），
    之后每次启动直接反序列化秒载。任一条件变化（源文件更新/参数不同）
    自动失效重建。返回 (lessons, warnings)。
    """
    import os as _os
    import pickle as _pk
    try:
        st = _os.stat(obk_path)
        meta = {
            "size": st.st_size,
            "mtime": int(st.st_mtime),
            "difficulty": difficulty,
            "max_lessons": max_lessons,
            "min_steps": min_steps,
            "prefix": start_id_prefix,
            "v": 2,  # 缓存格式版本：v2=含真难度分层（胜/和/负统计）
        }
    except OSError:
        meta = None
    cache_path = (obk_path + ".pkl.cache") if meta is not None else None
    if cache_path and _os.path.isfile(cache_path):
        try:
            with open(cache_path, "rb") as f:
                blob = _pk.load(f)
            bm = blob.get("meta") or {}
            # 宽松命中：源文件一致 + 生成参数一致（max_lessons 不参与失效判定，
            # 只要缓存课程数够用就截断返回——避免调用方动态请求数导致缓存反复失效）
            if (bm.get("v") == 2
                    and bm.get("size") == meta["size"]
                    and bm.get("mtime") == meta["mtime"]
                    and bm.get("difficulty") == difficulty
                    and bm.get("min_steps") == min_steps
                    and bm.get("prefix") == start_id_prefix
                    and blob.get("lessons")
                    and len(blob["lessons"]) >= max_lessons):
                return blob["lessons"][:max_lessons], blob.get("warns", [])
        except Exception:
            pass  # 缓存损坏 → 走正常解析并重建
    lessons, warns = _obk_to_lessons_impl(
        obk_path, difficulty=difficulty, max_lessons=max_lessons,
        min_steps=min_steps, start_id_prefix=start_id_prefix,
    )
    if cache_path and lessons:
        try:
            with open(cache_path, "wb") as f:
                _pk.dump({"meta": meta, "lessons": lessons, "warns": warns},
                         f, protocol=_pk.HIGHEST_PROTOCOL)
        except Exception:
            pass
    return lessons, warns


def _obk_to_lessons_impl(
    obk_path: str,
    *,
    difficulty: int = 2,
    max_lessons: int = 120,
    min_steps: int = 8,
    start_id_prefix: str = "obk",
) -> tuple[list[OpeningLesson], list[str]]:
    """真正的 OBK 解析实现（被 obk_to_lessons 的缓存层包装调用）。"""
    import time as _t
    from ..board.board import Board
    from ..board.position import parse_ucci_move
    from ..board import rules as _rules
    from ..board.notation import move_to_chinese

    # 1. 加载 move_int->weight 聚合（153MB 大约 5~10 秒）
    wmap = _obk_load_move_weights(obk_path)
    if "__err__" in wmap:
        return [], [f"OBK 加载失败（bhobk 表或格式不对）：{wmap['__err__']}"]
    if len(wmap) < 1000:
        return [], [f"OBK move 聚合过少（仅 {len(wmap)} 条），非开局库 OBK 或表结构不兼容。"]

    warnings: list[str] = [f"OBK move 权重聚合 OK（{len(wmap):,} 个不同走子）"]
    stamp = str(int(_t.time() * 1000) % 1_000_000)
    MAX_DEPTH = 30
    # 每条谱链的难度信号：tuple(chain) -> dict(avg_draw, avg_branch, trick)
    chain_sig: dict[tuple, dict] = {}

    def _board_from_moves(mvs: list[str]) -> Board:
        bb = Board.start_position()
        for u in mvs:
            frm, to = parse_ucci_move(u)
            if not _rules.is_legal(bb, frm, to):
                raise ValueError(u)
            bb.make_move(frm, to)
        return bb

    def _greedy_chain(board0: Board, max_depth: int, cur_ply: int):
        """贪心走主链，返回 (moves, sig)；sig=难度信号（和棋率/分叉/飞刀）。"""
        out: list[str] = []
        draws: list[float] = []
        branches: list[int] = []
        trick = False
        b = board0
        ply = cur_ply
        for _ in range(max_depth):
            lst = _cands_from_wmap(b, wmap, topk=5, ply_hint=ply)
            if not lst:
                break
            mv_u = lst[0][0]
            base_w, bwin, bdraw, blost = lst[0][2]
            n_tot = bwin + bdraw + blost
            if n_tot > 0:
                draws.append(bdraw / n_tot)
                # 飞刀信号：库中低频招（base_w 低）但实战胜率明显高
                if base_w < 300_000 and (bwin / n_tot) > 0.55:
                    trick = True
            branches.append(len(lst))
            frm, to = parse_ucci_move(mv_u)
            if not _rules.is_legal(b, frm, to):
                break
            out.append(mv_u)
            b.make_move(frm, to)
            ply += 1
        sig = {
            "avg_draw": (sum(draws) / len(draws)) if draws else 0.5,
            "avg_branch": (sum(branches) / len(branches)) if branches else 1.0,
            "trick": trick,
        }
        return out, sig

    def _diff_from_sig(sig: dict) -> int:
        """难度信号 → 1~5 星。和棋率高+分叉少=入门定式；胜负分明+多分叉+飞刀=高难。"""
        score = 0
        ab = sig.get("avg_branch", 1.0)
        score += 2 if ab >= 2.5 else (1 if ab >= 1.8 else 0)
        ad = sig.get("avg_draw", 0.5)
        score += 2 if ad < 0.30 else (1 if ad < 0.45 else 0)
        if sig.get("trick"):
            score += 2
        return 1 + min(4, score)

    _DIFF_LABEL = {1: "入门定式", 2: "基础谱", 3: "进阶变化", 4: "激烈复杂", 5: "飞刀陷阱"}

    start = Board.start_position()
    # 第一层：根招（起始局面第一手，取 TOP 12 个不同走子）
    root_cands = _cands_from_wmap(start, wmap, topk=12, ply_hint=0)
    collected: list[list[str]] = []

    def _chain_ok(ch: list[str]) -> bool:
        return len(ch) >= min_steps

    for cand_ucci, _cand_w, _cand_st in root_cands:
        if len(collected) >= max_lessons:
            break
        frm, to = parse_ucci_move(cand_ucci)
        if not _rules.is_legal(start, frm, to):
            continue
        try:
            bd_branch = _board_from_moves([cand_ucci])
        except ValueError:
            continue
        tail, tail_sig = _greedy_chain(bd_branch, MAX_DEPTH - 1, 1)  # 已走1步=ply=1
        full = [cand_ucci] + tail
        if _chain_ok(full):
            collected.append(full)
            chain_sig[tuple(full)] = tail_sig
        # 第二层：沿主链前进，中途分叉点（合法≥2候选）的[1:]变例各开一条课
        cur_bd = Board.start_position()
        cur_mvs: list[str] = []
        for idx_step, uu in enumerate(full):
            if len(collected) >= max_lessons:
                break
            mid_cands = _cands_from_wmap(cur_bd, wmap, topk=10, ply_hint=len(cur_mvs))
            if len(mid_cands) >= 2:
                branch_cands = mid_cands[1:]
                for mc_ucci, _mc_w, _mc_st in branch_cands:
                    if len(collected) >= max_lessons:
                        break
                    frm3, to3 = parse_ucci_move(mc_ucci)
                    if not _rules.is_legal(cur_bd, frm3, to3):
                        continue
                    try:
                        bd_mid_branch = _board_from_moves(cur_mvs + [mc_ucci])
                    except ValueError:
                        continue
                    mid_tail, mid_sig = _greedy_chain(
                        bd_mid_branch, MAX_DEPTH - len(cur_mvs) - 1, len(cur_mvs) + 1
                    )
                    mid_full = cur_mvs + [mc_ucci] + mid_tail
                    if _chain_ok(mid_full):
                        collected.append(mid_full)
                        chain_sig[tuple(mid_full)] = mid_sig
            # 前进
            frm2, to2 = parse_ucci_move(uu)
            if _rules.is_legal(cur_bd, frm2, to2):
                cur_mvs.append(uu)
                cur_bd.make_move(frm2, to2)
            else:
                break

    # 去重
    dedup: list[list[str]] = []
    seen_chains: set[tuple] = set()
    safe_cnt = 0
    unsafe_skip = 0
    for ch in collected:
        # 全链 SAFE 二次检查（盲匹配可能有垃圾分支，直接过滤掉不合法段）
        try:
            _bd_safe = Board.start_position()
            for u in ch:
                frm, to = parse_ucci_move(u)
                if not _rules.is_legal(_bd_safe, frm, to):
                    raise ValueError
                _bd_safe.make_move(frm, to)
            safe_cnt += 1
        except Exception:
            unsafe_skip += 1
            continue
        k = tuple(ch)
        if k in seen_chains:
            continue
        seen_chains.add(k)
        dedup.append(ch)
        if len(dedup) >= max_lessons:
            break
    if unsafe_skip > 0:
        warnings.append(f"盲匹配过滤：丢弃 {unsafe_skip} 条不合法分支（正常现象）。")
    warnings.append(f"最终 SAFE 去重后：{len(dedup)} 条独立开局谱链。")

    # 包装 OpeningLesson（和 bin_to_lessons 格式一致）
    wrapped: list[OpeningLesson] = []
    for i, mvs in enumerate(dedup):
        if len(mvs) < min_steps:
            continue
        try:
            bd = Board.start_position()
            step_names = []
            for uu in mvs[:6]:
                frm, to = parse_ucci_move(uu)
                step_names.append(move_to_chinese(bd, frm, to))
                bd.make_move(frm, to)
        except Exception:
            step_names = [mvs[0] if mvs else "obk"]
        cat = _guess_bin_lesson_category(mvs, fallback_hay="玫瑰飞刀库")
        short_title = "·".join(step_names[:3])
        # 真难度：由 OBK 胜/和/负统计 + 分叉 + 飞刀信号计算（fallback 传入 difficulty）
        sig = chain_sig.get(tuple(mvs), {})
        real_diff = _diff_from_sig(sig) if sig else difficulty
        diff_label = _DIFF_LABEL.get(real_diff, "进阶变化")
        title = f"{short_title}…（{len(mvs)}步·OBK飞刀库#{i+1}）"
        intro = (
            f"开局课（{cat}）\n"
            f"来源：OBK 玫瑰飞刀库（盲匹配展开第 {i+1} 条谱招链）\n"
            f"难度：{'★' * real_diff}{'☆' * (5 - real_diff)}〔{diff_label}〕"
            f"  共 {len([mm for ix, mm in enumerate(mvs) if ix % 2 == 0])} 红步。\n"
            "开局三原则：大子尽快出动、占据要道、不重复走子不贪吃。\n"
            "本课程由 OBK 开局库自动生成，教练会按谱招检查你的每一步。"
        )
        comments: dict[str, str] = {}
        bd2 = Board.start_position()
        for ix, uu in enumerate(mvs):
            frm, to = parse_ucci_move(uu)
            cn = move_to_chinese(bd2, frm, to)
            who = "红方" if ix % 2 == 0 else "黑方"
            turn = f"第{(ix // 2) + 1}回合{('红' if ix % 2 == 0 else '黑')}步"
            if ix < 8:
                comments[uu] = (
                    f"{turn}：{who}{cn}。《{title[:14]}…》开场基础定式招法，"
                    f"按谱练习形成肌肉记忆。"
                )
            else:
                comments[uu] = f"{turn}：{who}{cn}。飞刀谱进入中局延伸，抢占要道控制肋线。"
            bd2.make_move(frm, to)
        summary = (
            f"恭喜通关《{title}》！\n"
            f"本局共 {len(mvs)} 半步（{len([x for ix, x in enumerate(mvs) if ix % 2 == 0])} 红步）。\n"
            f"开场定式：{' → '.join(step_names[:8])}\n"
            "同类型的飞刀分支要多练几条，实战中才能识别陷阱与反制手段。"
        )
        wrapped.append(OpeningLesson(
            id=f"{start_id_prefix}_{stamp}_{i+1}",
            title=title,
            category=cat,
            difficulty=real_diff,
            side=Color.RED,
            intro=intro,
            summary=summary,
            moves=list(mvs),
            comments=comments,
            variations=[],
            pitfalls={},
        ))
    return wrapped, warnings
