"""开局课程库（初学者向，教练口吻，详细讲解版）。

课程主线均为双方合走的 UCCI 序列，自初始局面起全部经规则引擎逐半步验证合法。
训练方式：用户执 lesson.side 一方，沿主线走自己的着法；
走对了给讲解，走偏了提示正着与原因；对手着法由"教练"按谱自动走出。

UCCI 记号：如 "h2e2" = 炮二平五。
"""
from dataclasses import dataclass, field
from typing import Dict, List

from ..board.pieces import Color


@dataclass
class Pitfall:
    """一步正着的『偏着惩罚演示』：如果不走这步，会发生什么？"""
    title: str                       # 如 "偏着演示·跳边马，中兵失守"
    wrong: str                       # 偏着 UCCI（同时是 line[0]）
    line: List[str]                  # 演示线：偏着起双方合走 UCCI 序列
    comments: Dict[int, str]         # 半步索引 -> 该步讲解
    conclusion: str                  # 结论：损失了什么


@dataclass
class Variation:
    """开局变例：从主线某一分叉点派生出的不同走法分支。
    用于在主线完成后，展示『如果对方/我方换一种走法会怎样』，
    帮助学员理解开局谱的广度，而非死记一条主线。"""
    name: str                       # 变例名称，如 "黑方左横车变例"
    branch_at: str                  # 分叉点 UCCI（主线中由此步后开始分叉；空串表示从开局起就不同）
    moves: List[str]                # 变例主线 UCCI 序列（自初始局面，与原主线平行展示）
    explanation: str                # 变例说明：为何会转入此变例、双方意图、后续走向


@dataclass
class OpeningLesson:
    """一门开局课"""
    id: str
    title: str
    category: str            # 如 "开局/中炮"
    difficulty: int          # 1-5
    side: Color              # 用户执方
    intro: str               # 教练开场白
    summary: str             # 完成总结
    moves: List[str]         # 主线双方合走 UCCI 序列（自初始局面）
    comments: Dict[str, str] = field(default_factory=dict)  # ucci -> 该步讲解
    pitfalls: Dict[str, Pitfall] = field(default_factory=dict)  # 正着ucci -> 偏着演示
    variations: List[Variation] = field(default_factory=list)  # 变例分支图谱（可选）


