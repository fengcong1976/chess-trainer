def bin_to_lessons(
    bin_path: str,
    *,
    difficulty: int = 2,
    max_lessons: int = 100,
    min_steps: int = 8,
    start_id_prefix: str = "bin",
) -> tuple[list[OpeningLesson], list[str]]:
    """读入一个 Xiangqi Polyglot .bin 开局书，展开成多条 OpeningLesson。

    返回 (lessons, warnings)。展开策略：
      1) 从起始局面 startpos 出发，DFS 贪心按权重最大先走，遇到有 ≥2 步合法招且未展开就分叉；
      2) 每条 ≥ min_steps（默认 8 步）的独立走子链生成 1 课；
      3) 最多生成 max_lessons 课（默认100）避免大库卡死。
    """
    import time as _t
    from ..board.board import Board
    from ..board.position import parse_ucci_move
    from ..board import rules as _rules
    from ..board.notation import move_to_chinese
    from ..engine.opening_book import OpeningBook

    ob = OpeningBook()
    if not ob.load_bin(bin_path):
        return [], [f"无法加载 .bin 开局书：{bin_path}"]

    warnings: list[str] = []
    stamp = str(int(_t.time() * 1000) % 1_000_000)

    def _board_from_moves(mvs: list[str]) -> Board:
        bb = Board.start_position()
        for u in mvs:
            frm, to = parse_ucci_move(u)
            if not _rules.is_legal(bb, frm, to):
                raise ValueError(u)
            bb.make_move(frm, to)
        return bb

    def _greedy_chain(board0: Board, max_depth: int) -> list[str]:
        """从 board0 出发，贪心按最高权重走 max_depth 步，返回 moves 链。"""
        out: list[str] = []
        b = board0
        for _ in range(max_depth):
            h = ob.query(b, max_entries=3)
            if not h:
                break
            mv_u = h[0].ucci
            frm, to = parse_ucci_move(mv_u)
            if not _rules.is_legal(b, frm, to):
                break
            out.append(mv_u)
            b.make_move(frm, to)
        return out

    MAX_DEPTH = 30
    # -------- 简单可靠的两层展开：根招分支 + 每条主链的中途分叉 --------
    start = Board.start_position()
    root_candidates = ob.query(start, max_entries=40)
    collected: list[list[str]] = []

    def _chain_ok(ch: list[str]) -> bool:
        return len(ch) >= min_steps

    # 第一层：每个根招（开局第一手候选）→ 贪心到底 = 一课（常见开局，10~40条足够）
    for cand in root_candidates:
        if len(collected) >= max_lessons:
            break
        frm, to = parse_ucci_move(cand.ucci)
        if not _rules.is_legal(start, frm, to):
            continue
        bd_branch = _board_from_moves([cand.ucci])
        tail = _greedy_chain(bd_branch, MAX_DEPTH - 1)
        full = [cand.ucci] + tail
        if _chain_ok(full):
            collected.append(full)
        # 第二层：沿「根招主链」前进，中途每遇到分叉再展开一条变例课（同开局的变着）
        # 注意：这里沿 full 自己前进，沿途每个中间局面 query 找分叉
        cur_bd = Board.start_position()
        cur_mvs: list[str] = []
        for idx_step, uu in enumerate(full):
            if len(collected) >= max_lessons:
                break
            # 在走 uu 之前，先看「当前中间局面 cur_bd」有没有 ≥2 条候选招（分叉点）
            mid_cands = ob.query(cur_bd, max_entries=12)
            if len(mid_cands) >= 2:
                # mid_cands[0] 是主招（= uu 或 该局面最高权重招），mid_cands[1:] 为变例分支
                branch_cands = mid_cands[1:]
                for mc in branch_cands:
                    if len(collected) >= max_lessons:
                        break
                    frm3, to3 = parse_ucci_move(mc.ucci)
                    if not _rules.is_legal(cur_bd, frm3, to3):
                        continue
                    bd_mid_branch = _board_from_moves(cur_mvs + [mc.ucci])
                    mid_tail = _greedy_chain(
                        bd_mid_branch, MAX_DEPTH - len(cur_mvs) - 1
                    )
                    mid_full = cur_mvs + [mc.ucci] + mid_tail
                    if _chain_ok(mid_full):
                        collected.append(mid_full)
            # 前进：把 uu 在 cur_bd 上走掉
            frm2, to2 = parse_ucci_move(uu)
            if _rules.is_legal(cur_bd, frm2, to2):
                cur_mvs.append(uu)
                cur_bd.make_move(frm2, to2)
            else:
                break

    # 去重：同一 moves 链只保留 1 条
    dedup: list[list[str]] = []
    seen_chains: set[tuple] = set()
    for ch in collected:
        k = tuple(ch)
        if k in seen_chains:
            continue
        seen_chains.add(k)
        dedup.append(ch)
        if len(dedup) >= max_lessons:
            break
    lessons_list = dedup
    wrapped: list[OpeningLesson] = []
    for i, mvs in enumerate(lessons_list):
        if len(mvs) < min_steps:
            continue
        # 标题：前 3 步中文记法拼接（例：炮二平五·马8进7·马二进三…共X步）
        try:
            bd = Board.start_position()
            step_names = []
            for uu in mvs[:6]:
                frm, to = parse_ucci_move(uu)
                step_names.append(move_to_chinese(bd, frm, to))
                bd.make_move(frm, to)
        except Exception:
            step_names = [mvs[0] if mvs else "bin"]
        cat = _guess_bin_lesson_category(mvs, fallback_hay="")
        short_title = "·".join(step_names[:3])
        title = f"{short_title}…（{len(mvs)}步·bin导入#{i+1}）"
        intro = (
            f"开局课（{cat}）\n"
            f"来源：.bin 开局书展开的第 {i+1} 条谱招链\n"
            f"难度：{'★' * difficulty}  共 {len([mm for ix, mm in enumerate(mvs) if ix % 2 == 0])} 红步。\n"
            "开局三原则：大子尽快出动、占据要道、不重复走子不贪吃。\n"
            "本课程由开局书自动生成，教练会严格按谱招检查你的每一步。"
        )
        # comments：每一步教练口吻注释
        comments: dict[str, str] = {}
        bd2 = Board.start_position()
        for ix, uu in enumerate(mvs):
            frm, to = parse_ucci_move(uu)
            cn = move_to_chinese(bd2, frm, to)
            who = "红方" if ix % 2 == 0 else "黑方"
            turn = f"第{(ix // 2) + 1}回合{('红' if ix % 2 == 0 else '黑')}步"
            if ix < 6:
                comments[uu] = f"{turn}：{who}{cn}。这是《{title}》开场的基础定式招法，严格按谱走。"
            else:
                comments[uu] = f"{turn}：{who}{cn}。进入定式中局延伸，控制河沿抢占肋道。"
            bd2.make_move(frm, to)
        summary = (
            f"恭喜通关《{title}》！\n"
            f"本局共走了 {len(mvs)} 半步（{len([x for ix, x in enumerate(mvs) if ix%2==0])} 红步）。\n"
            f"前几步定式：{' → '.join(step_names[:6])}\n"
            "建议把同一分类下的多条谱链都练熟，形成开局面覆盖。"
        )
        wrapped.append(OpeningLesson(
            id=f"{start_id_prefix}_{stamp}_{i+1}",
            title=title,
            category=cat,
            difficulty=difficulty,
            side=Color.RED,  # bin 开局书统一默认红方视角开局（如果需黑方在开局训练里flip）
            intro=intro,
            summary=summary,
            moves=list(mvs),
            comments=comments,
            variations=[],
            pitfalls={},
        ))
    return wrapped, warnings


